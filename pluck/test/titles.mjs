const BASE='http://127.0.0.1:7777';
const PAGE='https://bitmovin.com/demos/stream-test';
const delay=(ms)=>new Promise(r=>setTimeout(r,ms));
const created=await (await fetch(BASE+'/api/session',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({url:PAGE})})).json();
const id=created.session.id;
const ws=new WebSocket(BASE.replace('http','ws')+'/ws?session='+id);
await new Promise((r,j)=>{ws.addEventListener('open',r);ws.addEventListener('error',j);});
const vids=new Map();
ws.addEventListener('message',(ev)=>{ if(typeof ev.data!=='string')return; const m=JSON.parse(ev.data); if(m.type==='video'||m.type==='videoUpdate'){ if(!vids.has(m.video.id)) vids.set(m.video.id, m.video); } if(m.type==='pageInfo') console.log('pageInfo', JSON.stringify(m.title)); });
await delay(9000);
for (const v of vids.values()) console.log(v.kind, JSON.stringify(v.title), v.quality, v.url.slice(0,60));
ws.close(); await fetch(BASE+'/api/session/'+id,{method:'DELETE'});
process.exit(0);
